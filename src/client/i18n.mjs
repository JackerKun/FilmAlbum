export function installLocale() {
  const original = new WeakMap(),
    attributes = new WeakMap();
  let locale = localStorage.getItem('filmalbum-locale') || 'zh-CN',
    pending = false;
  const select = document.createElement('select');
  select.id = 'locale-switch';
  select.setAttribute('aria-label', 'Language / 语言');
  select.innerHTML = '<option value="zh-CN">简体中文</option><option value="en">English</option>';
  select.value = locale;
  document.querySelector('.top-actions')?.prepend(select);
  const translate = (text) => {
    const trim = text.trim();
    if (words[trim]) return text.replace(trim, words[trim]);
    return text.replace(
      /(▤|▦|◫|◎|▧|＋|↶|▣|⚄)\s*(.+)/,
      (_, icon, t) => icon + ' ' + (words[t] || t),
    );
  };
  function apply() {
    document.documentElement.lang = locale;
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (
        node.parentElement?.closest(
          'script,style,textarea,input,#locale-switch,[data-user-content]',
        )
      )
        continue;
      let entry = original.get(node);
      if (!entry || node.nodeValue !== entry.output) entry = { source: node.nodeValue };
      const output = locale === 'en' ? translate(entry.source) : entry.source;
      if (node.nodeValue !== output) node.nodeValue = output;
      entry.output = output;
      original.set(node, entry);
    }
    for (const el of document.querySelectorAll('[placeholder],[aria-label],[title]')) {
      if (el.id === 'locale-switch') continue;
      let saved = attributes.get(el) || {};
      for (const key of ['placeholder', 'aria-label', 'title'])
        if (el.hasAttribute(key)) {
          const current = el.getAttribute(key);
          let entry = saved[key];
          if (!entry || current !== entry.output) entry = { source: current };
          entry.output = locale === 'en' ? translate(entry.source) : entry.source;
          if (current !== entry.output) el.setAttribute(key, entry.output);
          saved[key] = entry;
        }
      attributes.set(el, saved);
    }
  }
  const observer = new MutationObserver(() => {
    if (pending) return;
    pending = true;
    queueMicrotask(() => {
      pending = false;
      observer.disconnect();
      apply();
      observe();
    });
  });
  function observe() {
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['placeholder', 'aria-label', 'title'],
    });
  }
  select.onchange = () => {
    locale = select.value;
    localStorage.setItem('filmalbum-locale', locale);
    observer.disconnect();
    apply();
    observe();
  };
  apply();
  observe();
  return {
    get locale() {
      return locale;
    },
  };
}
